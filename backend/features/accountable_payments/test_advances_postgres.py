    def allocate(self, act=1, amount=6000, revision=0, payment=1):
        return self.client.put(f'/accountable-payments/{payment}/allocations',json={'actId':act,'amount':amount,'expectedRevision':revision})

    def test_manual_two_packages_reload_and_pay_server_remaining(self):
        self.assertEqual(self.allocate().status_code,200)
        self.assertEqual(self.allocate(act=2,amount=4000,revision=1).status_code,200)
        rows=self.client.get('/accountable-payments').json()
        payment=next(p for p in rows if p['id']==1)
        self.assertEqual(sum(a['amount'] for a in payment['allocations']),10000)
        self.assertEqual(payment['revision'],2)
        acts=self.client.get('/interim-acts').json();act=next(a for a in acts if a['id']==1)
        self.assertEqual((act['paidAmount'],act['advanceAmount'],act['remainingAmount']),(0,6000,4000))
        self.assertEqual(self.client.post('/interim-acts/1/pay',json={'amount':4001}).status_code,400)
        paid=self.client.post('/interim-acts/1/pay',json={'amount':4000})
        self.assertEqual(paid.status_code,200,paid.text)
        self.assertEqual(paid.json()['status'],'Оплачен')
        self.assertEqual(paid.json()['remainingAmount'],0)
        self.assertEqual(self.allocate(amount=1,revision=2).status_code,409)

    def test_two_tabs_cannot_over_allocate_or_replay(self):
        with ThreadPoolExecutor(max_workers=2) as pool:
            responses=list(pool.map(lambda act:self.allocate(act=act,amount=7000),[1,2]))
        self.assertEqual(sorted(r.status_code for r in responses),[200,409])
        self.assertEqual(self.sql('SELECT sum(amount) FROM performer_advance_allocations')[0][0],7000)
        self.assertEqual(self.allocate(amount=7000).status_code,409)
        self.assertEqual(self.sql('SELECT count(*) FROM performer_advance_events')[0][0],1)

