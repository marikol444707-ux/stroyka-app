    def test_payment_and_allocation_conserve_act_balance_when_concurrent(self):
        with ThreadPoolExecutor(max_workers=2) as pool:
            first=pool.submit(self.allocate,amount=7000)
            second=pool.submit(self.client.post,'/interim-acts/1/pay',json={'amount':7000})
            responses=[first.result(),second.result()]
        self.assertEqual(sum(r.status_code==200 for r in responses),1)
        result=next(a for a in self.client.get('/interim-acts').json() if a['id']==1)
        self.assertEqual(result['paidAmount']+result['advanceAmount'],7000)
        self.assertEqual(result['remainingAmount'],3000)

