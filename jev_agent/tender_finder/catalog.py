BY_ID = {topic.id: topic for topic in TOPICS}
_ALIASES = {}
for _topic in TOPICS:
    for _name in (_topic.id, _topic.name, _topic.query, *_topic.aliases):
        _key = normalized_text(_name)
        if _key in _ALIASES and _ALIASES[_key] != _topic.id:
            raise RuntimeError('Ambiguous topic alias')
        _ALIASES[_key] = _topic.id


def resolve_topic(name):
    return _ALIASES.get(normalized_text(name)) if isinstance(name, str) else None
